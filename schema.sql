-- schema.sql
DROP TABLE IF EXISTS person_got;
DROP TABLE IF EXISTS people_left;
DROP TABLE IF EXISTS all_people;

CREATE TABLE all_people (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL UNIQUE
);

CREATE TABLE people_left (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL UNIQUE
);

CREATE TABLE person_got (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  person TEXT NOT NULL UNIQUE,
  persongot TEXT NOT NULL
);